import { backgroundRefresh } from './refresh'
import { expect, test, type Page } from '@playwright/test'

async function login(page: Page) {
  await page.goto('/supplies/new?returnTo=%2Fsupplies%3Fsearch%3DН-')
  await page.getByLabel('Email', { exact: false }).fill('employee@example.test')
  await page.getByLabel(/^Пароль/).fill('local-test-only')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Новая поставка' })).toBeVisible()
  await expect(page.getByLabel('Продукт, строка 1', { exact: false })).toBeEnabled()
}
async function fill(page: Page, row = 1, product = 'Молоко', quantity = '1,000001') {
  if (row === 1) {
    await page.getByLabel(/^Номер поставки/).fill('Н-101')
    await page.getByLabel(/^Дата приёмки/).fill('2098-01-01T12:00')
  }
  await page.getByLabel(`Продукт, строка ${row}`, { exact: false }).selectOption({ label: product })
  await expect(page.getByLabel(`Единица, строка ${row}`)).toHaveValue(product === 'Яйцо' ? 'pcs' : 'l')
  await page.getByLabel(`Количество, строка ${row}`, { exact: false }).fill(quantity)
  await page.getByLabel(`Годен до, строка ${row}`, { exact: false }).fill('2099-01-01T12:00')
}
for (const width of [360, 390, 1024, 1440]) {
  test(`reception repeated batches, keyboard and result navigation at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1100 })
    const errors: string[] = []
    page.on('pageerror', (error) => errors.push(error.message))
    await login(page); await fill(page)
    await page.getByRole('button', { name: 'Добавить строку' }).focus(); await page.keyboard.press('Enter')
    await fill(page, 2)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `test-results/reception-form-${width}.png`, fullPage: true })
    await page.getByRole('button', { name: 'Принять поставку' }).focus(); await page.keyboard.press('Enter')
    await expect(page.getByRole('heading', { name: 'Поставка принята' })).toBeVisible()
    const received = width <= 1100 ? page.getByRole('region', { name: 'Принятые партии' }).getByRole('listitem') : page.getByRole('table', { name: 'Принятые партии' }).getByRole('row').filter({ has: page.locator('td') })
    await expect(received).toHaveCount(2)
    await expect(received.getByText('1,000001 л', { exact: true })).toHaveCount(2)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const readableLink = await page.getByRole('link', { name: 'Детали принятой поставки' }).evaluate((link) => { const style = getComputedStyle(link); return style.color !== style.backgroundColor })
    expect(readableLink).toBe(true)
    await page.screenshot({ path: `test-results/reception-result-${width}.png`, fullPage: true })
    await page.getByRole('link', { name: 'Детали принятой поставки' }).click()
    await expect(page.getByRole('heading', { name: 'Поставка Н-101' })).toBeVisible()
    const details = width <= 1100 ? page.getByRole('region', { name: 'Состав поставки' }).getByRole('listitem') : page.getByRole('table', { name: 'Состав поставки' }).getByRole('row').filter({ has: page.locator('td') })
    await expect(details).toHaveCount(2)
    await page.getByRole('link', { name: 'На склад: Молоко, строка 2' }).click()
    const selection = page.getByRole('region', { name: 'Выбор из поставки' })
    await selection.getByLabel('Сортировка партий').selectOption('-created_at')
    await expect(selection.getByText('Выбранная поставка')).toHaveCount(2)
    expect(errors).toEqual([])
  })
}

test('lost successful response survives reload and replays the identical key/body without duplicate reception', async ({ page }) => {
  const attempts: { key: string | undefined; body: string | null }[] = []
  page.on('request', (request) => { if (request.method() === 'POST' && new URL(request.url()).pathname === '/api/v1/supplies') attempts.push({ key: request.headers()['idempotency-key'], body: request.postData() }) })
  await login(page); await fill(page)
  await page.getByLabel('Сценарий API').selectOption('reception-lost-response')
  await page.getByRole('button', { name: 'Принять поставку' }).click()
  await expect(page.getByRole('button', { name: 'Повторить исходный запрос' })).toBeVisible()
  await expect(page.getByLabel(/^Номер поставки/)).toBeDisabled()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Повторить исходный запрос' })).toBeVisible()
  await expect(page.getByLabel(/^Номер поставки/)).toHaveValue('Н-101')
  await page.getByRole('button', { name: 'Повторить исходный запрос' }).click()
  await expect(page.getByRole('heading', { name: 'Поставка принята' })).toBeVisible()
  expect(attempts).toHaveLength(2); expect(attempts[1]).toEqual(attempts[0])
  expect(await page.evaluate(() => sessionStorage.getItem('flagman.reception.v1'))).toBeNull()
  await page.getByRole('link', { name: 'К истории поставок' }).click()
  await expect(page.getByRole('link', { name: 'Поставка Н-101', exact: true })).toHaveCount(1)
})

test('422 focuses original last row; 409 preserves form; corrections use fresh keys; sending locks order', async ({ page }) => {
  const keys: string[] = []
  page.on('request', (request) => { if (request.method() === 'POST' && new URL(request.url()).pathname === '/api/v1/supplies') keys.push(request.headers()['idempotency-key']) })
  await login(page); await fill(page)
  await page.getByRole('button', { name: 'Добавить строку' }).click(); await fill(page, 2, 'Яйцо', '2')
  await page.getByLabel('Сценарий API').selectOption('reception-validation')
  await page.getByRole('button', { name: 'Принять поставку' }).click()
  await expect(page.getByText('Срок этой партии уже истёк на сервере.')).toBeVisible()
  await expect(page.getByLabel('Годен до, строка 2', { exact: false })).toBeFocused()
  await page.getByLabel('Сценарий API').selectOption('reception-conflict')
  await page.getByRole('button', { name: 'Принять поставку' }).click()
  await expect(page.getByText('Этот номер уже принят.')).toBeVisible()
  await expect(page.getByLabel('Количество, строка 2', { exact: false })).toHaveValue('2')
  await page.getByLabel(/^Номер поставки/).fill('Н-102')
  await page.getByLabel('Сценарий API').selectOption('reception-slow')
  await page.getByRole('button', { name: 'Принять поставку' }).click()
  await expect(page.getByRole('button', { name: 'Добавить строку' })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Удалить строку 2' })).toBeDisabled()
  await expect(page.getByRole('heading', { name: 'Поставка принята' })).toBeVisible()
  expect(new Set(keys).size).toBe(3)
})

test('local quantity/date validation, empty catalogue, error retry and loading', async ({ page }) => {
  await login(page)
  await page.getByRole('button', { name: 'Принять поставку' }).click()
  await expect(page.getByText('Укажите номер поставки.')).toBeVisible()
  await expect(page.getByLabel(/^Номер поставки/)).toBeFocused()
  await fill(page, 1, 'Яйцо', '1.5')
  await page.getByLabel('Годен до, строка 1', { exact: false }).fill('2098-01-01T12:00')
  await page.getByRole('button', { name: 'Принять поставку' }).click()
  await expect(page.getByText('Количество штук должно быть целым.')).toBeVisible()
  await expect(page.getByText('Срок годности должен быть позже приёмки.')).toBeVisible()
  await page.getByLabel('Сценарий API').selectOption('products-empty')
  await expect(page.getByRole('heading', { name: 'Нет активных продуктов' })).toBeVisible()
  await page.getByLabel('Сценарий API').selectOption('products-error')
  await expect(page.getByRole('heading', { name: 'Не удалось загрузить продукты' })).toBeVisible()
  await backgroundRefresh(page, 'products-slow', '/api/v1/products', 'Загрузка продуктов', page.getByLabel(/^Номер поставки/))
  await expect(page.getByRole('heading', { name: 'Не удалось загрузить продукты' })).toBeHidden()
  await expect(page.getByLabel('Продукт, строка 1', { exact: false })).toBeEnabled()
})

