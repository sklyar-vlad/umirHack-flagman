test('validation and fractional URL boundaries never silently change', async ({ page }) => {
  const requests: string[] = []
  page.on('request', (r) => { if (new URL(r.url()).pathname === '/api/v1/orders') requests.push(r.url()) })
  await login(page, '/orders?orders_search=ТЕСТ'); await expect(page.getByRole('link', { name: 'Заказ ТЕСТ-101' })).toBeVisible()
  const count = requests.length
  await page.getByLabel('Создана с (включительно)').fill('2026-10-11T00:00'); await page.getByLabel('Создана до (не включая)').fill('2026-10-10T00:00')
  await page.getByRole('button', { name: 'Найти', exact: true }).click(); await expect(page.getByLabel('Создана до (не включая)')).toHaveAttribute('aria-invalid', 'true')
  expect(requests).toHaveLength(count)
  await page.goto('/orders?orders_from=invalid'); await expect(page.getByRole('heading', { name: 'Некорректные фильтры' })).toBeVisible(); expect(requests).toHaveLength(count)
  const from = '2026-10-08T12:00:00.123456788Z', to = '2026-10-08T12:00:00.123456790Z'
  await page.goto(`/orders?orders_from=${from}&orders_to=${to}`)
  await expect(page.getByRole('link', { name: 'Заказ Буквальный %_\\' })).toBeVisible()
  await page.getByLabel('Номер заказа или название блюда').fill('Буквальный'); await page.getByLabel('Номер заказа или название блюда').press('Enter')
  await expect.poll(() => new URL(page.url()).searchParams.get('orders_search')).toBe('Буквальный')
  expect(new URL(page.url()).searchParams.get('orders_from')).toBe(from); expect(new URL(page.url()).searchParams.get('orders_to')).toBe(to)
  await page.goto('/orders?tab=attempts&attempts_reason_code=NETWORK_ERROR'); await expect(page.getByRole('heading', { name: 'Некорректные фильтры' })).toBeVisible()
})
