test('server pagination, URL history, restaurant timezone boundaries and literal number search', async ({ page }) => {
  // Browser timezone deliberately differs from restaurant settings.
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await login(page, '/supplies?page_size=20')
  await expect(page.getByText('Найдено поставок: 26. Страница 1.')).toBeVisible()
  await page.getByRole('button', { name: 'Следующая страница' }).click()
  await expect(page.getByText('Найдено поставок: 26. Страница 2.')).toBeVisible()
  await page.getByLabel('Поиск по номеру').fill('ГРАНИЦА')
  await page.getByLabel('Создана с (включительно)').fill('2026-10-10T00:00')
  await page.getByLabel('Создана до (не включая)').fill('2026-10-11T00:00')
  await page.getByLabel('Поиск по номеру').press('Enter')
  await expect(page.getByRole('link', { name: 'Поставка ГРАНИЦА-С' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Поставка ГРАНИЦА-ДО' })).toHaveCount(0)
  const url = new URL(page.url()), query = url.search
  expect(url.searchParams.has('page')).toBe(false)
  expect(url.searchParams.get('from')).toBe('2026-10-09T21:00:00Z')
  expect(url.searchParams.get('to')).toBe('2026-10-10T21:00:00Z')
  await page.reload()
  await expect(page.getByLabel('Создана с (включительно)')).toHaveValue('2026-10-10T00:00')
  await page.getByRole('link', { name: 'Поставка ГРАНИЦА-С' }).click()
  await expect(page.getByRole('heading', { name: 'Детали поставки' })).toBeVisible()
  await page.goBack()
  await expect(page).toHaveURL(`/supplies${query}`)
  await page.goForward()
  await expect(page.getByRole('heading', { name: 'Детали поставки' })).toBeVisible()
  await page.getByRole('link', { name: 'К истории поставок' }).click()
  await expect(page).toHaveURL(`/supplies${query}`)
  await page.getByRole('button', { name: 'Сбросить фильтры' }).click()
  await page.getByLabel('Поиск по номеру').fill('%_\\')
  await page.getByRole('button', { name: 'Найти', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Поставка Буквальный %_\\' })).toBeVisible()
  await expect(page.getByText('Найдено поставок: 1. Страница 1.')).toBeVisible()
})

test('validation associates the period error, invalid URL does not request, fractional bounds survive native form', async ({ page }) => {
  const requests: string[] = []
  page.on('request', (request) => { if (new URL(request.url()).pathname === '/api/v1/supplies') requests.push(request.url()) })
  await login(page, '/supplies?search=ТЕСТ')
  await expect(page.getByRole('link', { name: 'Поставка ТЕСТ-101' })).toBeVisible()
  const count = requests.length
  await page.getByLabel('Создана с (включительно)').fill('2026-10-11T00:00')
  await page.getByLabel('Создана до (не включая)').fill('2026-10-10T00:00')
  await page.getByRole('button', { name: 'Найти', exact: true }).click()
  await expect(page.getByText('Начало периода должно быть не позже конца.')).toBeVisible()
  await expect(page.getByLabel('Создана до (не включая)')).toHaveAttribute('aria-invalid', 'true')
  expect(requests).toHaveLength(count)
  await page.goto('/supplies?from=not-a-date')
  await expect(page.getByRole('heading', { name: 'Некорректный период' })).toBeVisible()
  expect(requests).toHaveLength(count)
  const from = '2026-10-08T12:00:00.123456788Z', to = '2026-10-08T12:00:00.123456790Z'
  await page.goto(`/supplies?from=${from}&to=${to}`)
  await expect(page.getByRole('link', { name: 'Поставка Буквальный %_\\' })).toBeVisible()
  await expect(page.getByLabel('Создана с (включительно)')).toHaveValue('2026-10-08T15:00:00.123')
  await page.getByLabel('Поиск по номеру').fill('Буквальный')
  await page.getByLabel('Поиск по номеру').press('Enter')
  await expect.poll(() => new URL(page.url()).searchParams.get('search')).toBe('Буквальный')
  expect(new URL(page.url()).searchParams.get('from')).toBe(from)
  expect(new URL(page.url()).searchParams.get('to')).toBe(to)
  await page.goto(`/supplies?from=${from}&to=${from}`)
  await expect(page.getByRole('heading', { name: 'Ничего не найдено' })).toBeVisible()
})

test('loading, current-list network recovery, no stale results for new filters, empty history and 403', async ({ page }) => {
  await login(page, '/supplies?search=ТЕСТ')
  const link = page.getByRole('link', { name: 'Поставка ТЕСТ-101' })
  await expect(link).toBeVisible()
  await page.getByLabel('Сценарий API').selectOption('slow')
  await expect(page.getByRole('status', { name: 'Загрузка поставок' })).toBeVisible()
  await expect(link).toBeVisible()
  await expect(page.getByRole('status', { name: 'Загрузка поставок' })).toHaveCount(0)
  await page.getByLabel('Сценарий API').selectOption('network-error')
  await expect(page.getByRole('heading', { name: 'Не удалось загрузить поставки' })).toBeVisible()
  await expect(page.getByText(/Данные могут быть устаревшими/)).toBeVisible()
  await expect(link).toBeVisible()
  await page.getByLabel('Поиск по номеру').fill('Нет такого номера')
  await page.getByLabel('Поиск по номеру').press('Enter')
  await expect(link).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Не удалось загрузить поставки' })).toBeVisible()
  await page.getByLabel('Сценарий API').selectOption('success')
  await expect(page.getByRole('heading', { name: 'Ничего не найдено' })).toBeVisible()
  await page.getByRole('button', { name: 'Сбросить фильтры' }).first().click()
  await expect(link).toBeVisible()
  await page.getByLabel('Сценарий API').selectOption('supplies-empty')
  await expect(page.getByRole('heading', { name: 'Поставок пока нет' })).toBeVisible()
  await page.getByLabel('Сценарий API').selectOption('success')
  await expect(link).toBeVisible()
  await page.getByLabel('Сценарий API').selectOption('forbidden')
  await expect(page.getByRole('heading', { name: 'Недостаточно прав' })).toBeVisible()
  await expect(link).toHaveCount(0)
  await expect(page.getByRole('banner').getByText('Тестовый сотрудник')).toBeVisible()
  await page.getByLabel('Сценарий API').selectOption('success')
  await expect(link).toBeVisible()
})

