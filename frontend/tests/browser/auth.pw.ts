import { expect, test, type Page } from '@playwright/test'

async function fillLogin(page: Page, password = 'local-test-only') {
  await page.getByLabel('Email', { exact: false }).fill('employee@example.test')
  await page.getByLabel(/^Пароль/).fill(password)
}
for (const width of [360, 390, 1024, 1440]) {
  test(`login validation, keyboard, pending, restoration and logout at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    const errors: string[] = []
    page.on('pageerror', (error) => errors.push(error.message))
    await page.goto('/login')
    await expect(page.getByRole('heading', { name: 'Вход в Кладовую' })).toBeVisible()
    await page.getByRole('button', { name: 'Войти', exact: true }).click()
    await expect(page.getByText('Введите корректный email.')).toBeVisible()
    await expect(page.getByText('Введите пароль.')).toBeVisible()
    await expect(page.getByLabel('Email', { exact: false })).toBeFocused()
    await fillLogin(page)
    await page.keyboard.press('Tab')
    await expect(page.getByRole('button', { name: 'Показать пароль' })).toBeFocused()
    await page.keyboard.press('Space')
    await expect(page.getByLabel(/^Пароль/)).toHaveAttribute('type', 'text')
    await page.keyboard.press('Space')
    await expect(page.getByLabel(/^Пароль/)).toHaveAttribute('type', 'password')
    await page.getByLabel('Сценарий API').selectOption('slow')
    await page.getByRole('button', { name: 'Войти', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Входим…' })).toBeDisabled()
    await expect(page.getByLabel('Email', { exact: false })).toBeDisabled()
    await expect(page.getByLabel(/^Пароль/)).toBeDisabled()
    await expect(page.getByRole('heading', { name: 'Обзор', exact: true })).toBeVisible()
    await page.getByLabel('Сценарий API').selectOption('success')
    await page.reload()
    await expect(page.getByText('Тестовый сотрудник', { exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const logoutRequests: string[] = []
    page.on('request', (request) => { if (new URL(request.url()).pathname === '/api/v1/auth/logout') logoutRequests.push(request.url()) })
    await page.getByRole('button', { name: 'Выйти', exact: true }).click()
    await expect(page).toHaveURL('/login')
    expect(logoutRequests).toHaveLength(1)
    await expect(page.getByText(/Сервер не подтвердил выход/)).toHaveCount(0)
    await expect(page.getByLabel(/^Пароль/)).toHaveValue('')
    expect(await page.evaluate(() => [JSON.stringify(localStorage), JSON.stringify(sessionStorage), location.href].join(' '))).not.toContain('local-test-only')
    await page.reload()
    await expect(page.getByRole('heading', { name: 'Вход в Кладовую' })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `test-results/login-${width}.png`, fullPage: true })
    expect(errors).toEqual([])
  })
}

test('invalid password, disabled account and rate limit stay on login without redirect loops', async ({ page }) => {
  await page.goto('/login?returnTo=https%3A%2F%2Fevil.test')
  await fillLogin(page, 'wrong-local-password')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'Неверный email или пароль.' })).toBeFocused()
  await expect(page.getByLabel(/^Пароль/)).toHaveValue('')
  await page.getByLabel('Сценарий API').selectOption('disabled-user')
  await fillLogin(page)
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByText('Учётная запись отключена или вход запрещён. Обратитесь к администратору.')).toBeVisible()
  await page.getByLabel('Сценарий API').selectOption('rate-limit')
  await fillLogin(page)
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByText(/Повторите вход через/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Войти', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Войти', exact: true })).toBeEnabled({ timeout: 4000 })
  await page.getByLabel('Сценарий API').selectOption('success')
  await fillLogin(page)
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page).toHaveURL('/')
})

test('restoration failure keeps protected content closed and supports explicit retry', async ({ page, context }) => {
  await context.addCookies([{ name: 'flagman_mock_session', value: 'active', url: 'http://127.0.0.1:5182' }])
  await page.goto('/dev/api')
  await expect(page.getByText('Моковый ответ получен')).toBeVisible()
  await page.getByLabel('Сценарий API').selectOption('server-error')
  await expect(page.getByRole('alert')).toBeVisible()
  await page.getByRole('link', { name: '← На главную' }).click()
  await expect(page.getByText('Не удалось проверить сессию. Повторите проверку перед продолжением.')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Обзор', exact: true })).not.toBeVisible()
  await page.getByLabel('Сценарий API').selectOption('success')
  await page.getByRole('button', { name: 'Попробовать снова' }).click()
  await expect(page.getByRole('heading', { name: 'Обзор', exact: true })).toBeVisible()
})

test('expired cookie sends a restored session to login once and permits login again', async ({ page, context }) => {
  const confirmed: string[] = []
  page.on('response', (response) => { if (new URL(response.url()).pathname === '/api/v1/auth/me' && response.ok()) confirmed.push(response.url()) })
  await page.goto('/login?returnTo=%2Flogin')
  await fillLogin(page)
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page).toHaveURL('/')
  await expect.poll(() => confirmed.length).toBe(2)
  await context.clearCookies()
  const me: string[] = []
  let restoredDocument = false
  page.on('framenavigated', (frame) => { if (frame === page.mainFrame()) restoredDocument = true })
  page.on('request', (request) => { if (restoredDocument && new URL(request.url()).pathname === '/api/v1/auth/me') me.push(request.url()) })
  await page.reload()
  await expect(page).toHaveURL('/login')
  await expect(page.getByRole('heading', { name: 'Вход в Кладовую' })).toBeVisible()
  expect(me).toHaveLength(1)
  await fillLogin(page)
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Обзор', exact: true })).toBeVisible()
})
