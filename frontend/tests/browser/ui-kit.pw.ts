import { test, expect } from '@playwright/test'

for (const width of [360, 390, 1024, 1440]) {
  test(`UI kit responsive and keyboard behavior at ${width}`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    const errors: string[] = []
    const apiRequests: string[] = []
    page.on('pageerror', (error) => errors.push(error.message))
    page.on('request', (request) => { if (request.url().includes('/api/v1/')) apiRequests.push(request.url()) })
    await page.goto('/dev/ui')
    await expect(page.getByRole('heading', { name: 'Компоненты интерфейса' })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await expect(page.getByRole('table', { name: 'Пример складских остатков' })).toBeVisible({ visible: width >= 768 })
    await expect(page.getByRole('region', { name: 'Пример складских остатков' })).toBeVisible({ visible: width < 768 })
    await page.keyboard.press('Tab')
    await expect(page.getByRole('link', { name: '← На главную' })).toBeFocused()
    await page.keyboard.press('Tab')
    const trigger = page.getByRole('button', { name: 'Открыть диалог' })
    await expect(trigger).toBeFocused()
    await page.keyboard.press('Enter')
    const dialog = page.getByRole('dialog', { name: 'Подтверждение действия с длинным названием' })
    await expect(dialog).toBeVisible()
    for (let i = 0; i < 6; i++) {
      await page.keyboard.press('Tab')
      // Browsers may focus the top-level document at the wrap boundary, but no background control is reachable.
      expect(await page.evaluate(() => document.activeElement === document.body || !!document.activeElement?.closest('dialog'))).toBe(true)
    }
    await page.keyboard.press('Escape')
    await expect(dialog).not.toBeVisible()
    await expect(trigger).toBeFocused()
    await page.getByRole('button', { name: 'Открыть боковую панель' }).click()
    const drawer = page.getByRole('dialog', { name: 'Параметры отображения' })
    await expect(drawer).toBeVisible()
    expect(await drawer.evaluate((el) => el.getBoundingClientRect().right <= innerWidth)).toBe(true)
    await drawer.getByRole('button', { name: 'Применить' }).click()
    await expect(page.getByRole('button', { name: 'Открыть боковую панель' })).toBeFocused()
    await page.getByRole('button', { name: 'Сохранить пример' }).click()
    await expect(page.getByRole('alert').filter({ hasText: 'Введите не менее двух символов' })).toBeVisible()
    await expect(page.getByRole('alert').filter({ hasText: 'Выберите категорию' })).toBeVisible()
    const name = page.getByLabel('Название продукта с длинной русской подписью для проверки переноса')
    await expect(name).toBeFocused()
    await name.fill('Моцарелла для ресторанной кухни')
    await page.getByLabel('Категория').selectOption('dairy')
    const checkbox = page.getByRole('checkbox', { name: 'Подтверждаю условия хранения и проверки срока годности' })
    await checkbox.focus()
    await page.keyboard.press('Space')
    await expect(checkbox).toBeChecked()
    const toggle = page.getByRole('switch', { name: 'Показывать уведомления об остатках' })
    await toggle.focus()
    await page.keyboard.press('Space')
    await expect(toggle).not.toBeChecked()
    await page.getByRole('link', { name: '← На главную' }).click()
    const guard = page.getByRole('dialog', { name: 'Уйти без сохранения?' })
    await expect(guard).toBeVisible()
    await expect(guard.getByRole('button', { name: 'Остаться' })).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(guard).not.toBeVisible()
    await expect(name).toHaveValue('Моцарелла для ресторанной кухни')
    await page.getByRole('button', { name: 'Сохранить пример' }).click()
    await expect(page.getByRole('button', { name: 'Сохраняем…' })).toBeDisabled()
    await expect(name).toBeDisabled()
    await expect(page.getByText('Нет несохранённых изменений', { exact: true })).toBeVisible()
    await expect(page.getByRole('status').filter({ hasText: 'Пример сохранён локально' })).toBeVisible()
    await page.getByRole('button', { name: 'Скрыть уведомление: Пример сохранён локально' }).click()
    await expect(page.getByText('Пример сохранён локально', { exact: true })).not.toBeVisible()
    await page.getByRole('button', { name: 'Следующая страница' }).click()
    await expect(page.getByRole('button', { name: 'Страница 2' })).toHaveAttribute('aria-current', 'page')
    await page.getByRole('button', { name: 'Сбросить фильтры' }).click()
    await expect(page.getByText('Попробуйте изменить запрос или фильтры.', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Попробовать снова' }).click()
    await expect(page.getByRole('button', { name: 'Повторяем…' })).toBeDisabled()
    await expect(page.getByText('Данные снова доступны', { exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `test-results/ui-kit-${width}.png`, fullPage: true })
    await name.fill('Новое несохранённое значение')
    await page.getByRole('link', { name: '← На главную' }).click()
    await guard.getByRole('button', { name: 'Уйти без сохранения' }).click()
    await expect(page).toHaveURL('/')
    expect(errors).toEqual([])
    expect(apiRequests).toEqual([])
  })
}

test('dirty form blocks tab closure and clean form allows closure', async ({ page }) => {
  await page.goto('/dev/ui')
  await page.getByLabel('Название продукта с длинной русской подписью для проверки переноса').fill('Сыр')
  let unloadDialogs = 0
  page.on('dialog', async (dialog) => { expect(dialog.type()).toBe('beforeunload'); unloadDialogs++; await dialog.dismiss() })
  await page.close({ runBeforeUnload: true })
  await expect.poll(() => unloadDialogs).toBe(1)
  expect(page.isClosed()).toBe(false)
  await expect(page.getByLabel('Название продукта с длинной русской подписью для проверки переноса')).toHaveValue('Сыр')
  await page.getByRole('button', { name: 'Сбросить форму' }).click()
  await expect(page.getByText('Нет несохранённых изменений', { exact: true })).toBeVisible()
  const closed = page.waitForEvent('close')
  await page.close({ runBeforeUnload: true })
  await closed
  expect(unloadDialogs).toBe(1)
})
