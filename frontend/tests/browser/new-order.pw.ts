test('recipe revision is visible and must be confirmed before any new check or submit', async ({ page }) => {
  const checks: string[] = []
  page.on('request', (request) => { if (new URL(request.url()).pathname === '/api/v1/orders/check') checks.push(request.postData()!) })
  await login(page); await addSoup(page); await expect(create(page)).toBeEnabled()
  await page.getByLabel('Сценарий API').selectOption('order-recipe-changed')
  const panel = page.getByRole('region', { name: 'Изменение рецептуры' })
  await expect(panel).toContainText('1 → 2'); await expect(panel).toContainText('150 мл'); await expect(create(page)).toBeDisabled()
  const count = checks.length
  await page.getByRole('button', { name: 'Подтверждаю актуальный состав' }).click(); await expect(create(page)).toBeEnabled()
  expect(checks.length).toBe(count + 1); expect(JSON.parse(checks.at(-1)!).items[0].recipe_version).toBe(2)
})
