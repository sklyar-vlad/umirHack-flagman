import { expect, test, type Page } from '@playwright/test'
async function login(page: Page, role = 'manager') {
  await page.goto('/login?returnTo=%2Forders%2Fnew')
  if (role !== 'manager') await page.getByLabel('Сценарий API').selectOption(`role-${role.replaceAll('_', '-')}`)
  await page.getByLabel(/^Email/).fill('employee@example.test'); await page.getByLabel(/^Пароль/).fill('local-test-only')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
}
async function addSoup(page: Page) { await page.getByRole('button', { name: 'Добавить Суп дня', exact: true }).click(); await expect(page.getByLabel(/^Порции: Суп дня/)).toBeVisible() }
const create = (page: Page) => page.getByRole('button', { name: 'Оформить заказ', exact: true })
for (const width of [360, 390, 1024, 1440]) {
  test(`catalogue, keyboard basket and actual multi-batch result at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 })
    const errors: string[] = [], posts: { body: string | null; key: string | undefined; csrf: string | undefined }[] = []
    page.on('pageerror', (error) => errors.push(error.message))
    page.on('request', (request) => { if (new URL(request.url()).pathname === '/api/v1/orders' && request.method() === 'POST') posts.push({ body: request.postData(), key: request.headers()['idempotency-key'], csrf: request.headers()['x-csrf-token'] }) })
    await login(page)
    await expect(page.getByRole('heading', { name: 'Новый заказ' })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Корзина пуста' })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Добавить Отключённое блюдо' })).toBeDisabled()
    await expect(page.getByRole('button', { name: 'Добавить Без рецептуры' })).toBeDisabled()
    await page.getByText('Состав: Суп дня', { exact: true }).focus(); await page.keyboard.press('Enter')
    await expect(page.getByText('Молоко — 100 мл на порцию', { exact: true }).filter({ visible: true })).toBeVisible()
    await page.getByRole('button', { name: 'Добавить Суп дня', exact: true }).focus(); await page.keyboard.press('Enter')
    await page.getByLabel(/^Порции: Суп дня/).fill('0'); await expect(page.getByLabel(/^Порции: Суп дня/)).toHaveAttribute('aria-invalid', 'true'); await expect(create(page)).toBeDisabled()
    await page.getByLabel(/^Порции: Суп дня/).fill('6'); await expect(create(page)).toBeEnabled()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `test-results/new-order-${width}.png`, fullPage: true })
    await create(page).focus(); await page.keyboard.press('Enter')
    await expect(page.getByRole('heading', { name: 'Заказ создан' })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Заказ №1001' })).toBeVisible()
    const result = page.getByRole('table', { name: 'Фактические списания: Суп дня' }).or(page.getByRole('region', { name: 'Фактические списания: Суп дня' })).filter({ visible: true })
    await expect(result).toContainText('500 мл'); await expect(result).toContainText('50 мл')
    await expect(page.getByRole('link', { name: 'К заказу №1001' })).toHaveAttribute('href', /\/orders\/[a-f\d-]{36}$/)
    await expect(page.getByRole('link', { name: 'Партия на складе' }).filter({ visible: true }).first()).toHaveAttribute('href', /product_id=.*supply_id=/)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `test-results/created-order-${width}.png`, fullPage: true })
    expect(posts).toHaveLength(1); expect(posts[0].key).toMatch(/^[a-f\d-]{36}$/); expect(posts[0].csrf).toBe('mock-csrf-for-local-tests')
    expect(JSON.parse(posts[0].body!).items).toEqual([{ dish_id: '00000000-0000-4000-8000-000000000800', portions: 6, recipe_version: 1 }])
    await page.getByRole('button', { name: 'Создать ещё заказ' }).click(); await expect(page.getByRole('heading', { name: 'Корзина пуста' })).toBeVisible()
    await expect(page.getByText('Отдельно доступно: 9 порц. Рецептура: 1.').first()).toBeVisible()
    expect(errors).toEqual([])
  })
}
