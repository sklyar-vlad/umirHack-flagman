import { expect, test, type Page } from '@playwright/test'

async function login(page: Page, role = 'manager', target = '/') {
  await page.goto(`/login${target === '/' ? '' : `?returnTo=${encodeURIComponent(target)}`}`)
  if (role !== 'manager') await page.getByLabel('Сценарий API').selectOption(`role-${role === 'order_operator' ? 'order-operator' : role}`)
  await page.getByLabel('Email', { exact: false }).fill('employee@example.test')
  await page.getByLabel(/^Пароль/).fill('local-test-only')
  await page.getByRole('button', { name: 'Войти', exact: true }).click()
}
async function navigation(page: Page, width = 1440) {
  if (width < 768) await page.getByRole('button', { name: 'Открыть меню' }).click()
  return page.getByRole('navigation', { name: 'Разделы приложения', exact: true })
}

for (const width of [360, 390, 1024, 1440]) {
  test(`shell, keyboard and history at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 })
    const errors: string[] = []
    page.on('pageerror', (error) => errors.push(error.message))
    await login(page)
    await expect(page.getByRole('heading', { name: 'Обзор', exact: true })).toBeVisible()
    const header = page.getByRole('banner')
    for (const text of ['Тестовый ресторан', 'Тестовый сотрудник', 'Менеджер']) await expect(header.getByText(text, { exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'Открыть меню' })).toBeVisible({ visible: width < 768 })
    const nav = await navigation(page, width)
    for (const title of ['Обзор', 'Склад', 'Поставки', 'Заказы', 'Стоп-лист', 'Рекомендации']) await expect(nav.getByRole('link', { name: title, exact: true })).toBeVisible()
    await expect(nav.getByRole('link', { name: 'Обзор', exact: true })).toHaveAttribute('aria-current', 'page')
    await expect(nav.getByRole('link', { name: 'Админ-панель', exact: true })).toHaveCount(0)
    if (width < 768) {
      const drawer = page.getByRole('dialog', { name: 'Меню', exact: true })
      for (let i = 0; i < 15; i++) {
        await page.keyboard.press('Tab')
        expect(await page.evaluate(() => document.activeElement === document.body || !!document.activeElement?.closest('dialog'))).toBe(true)
      }
      await page.keyboard.press('Escape')
      await expect(drawer).not.toBeVisible()
      await expect(page.getByRole('button', { name: 'Открыть меню' })).toBeFocused()
      await page.keyboard.press('Enter')
    }
    await nav.getByRole('link', { name: 'Склад', exact: true }).focus()
    await page.keyboard.press('Enter')
    await expect(page).toHaveURL('/inventory')
    await expect(page.getByRole('heading', { name: 'Склад', exact: true })).toBeVisible()
    await expect(page.getByRole('dialog', { name: 'Меню', exact: true })).not.toBeVisible()
    await page.reload()
    await expect(page.getByRole('heading', { name: 'Склад', exact: true })).toBeVisible()
    await page.goBack()
    await expect(page).toHaveURL('/')
    await page.goForward()
    await expect(page).toHaveURL('/inventory')
    await (await navigation(page, width)).getByRole('link', { name: 'Рекомендации', exact: true }).click()
    await expect(page).toHaveURL('/recommendations/offers')
    const tabs = page.getByRole('navigation', { name: 'Вкладки рекомендаций' })
    await tabs.getByRole('link', { name: 'Закупить продукты' }).click()
    await expect(page).toHaveURL('/recommendations/procurement')
    await expect(tabs.getByRole('link', { name: 'Закупить продукты' })).toHaveAttribute('aria-current', 'page')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `test-results/navigation-${width}.png`, fullPage: true })
    expect(errors).toEqual([])
  })
}

for (const role of ['admin', 'manager', 'storekeeper', 'order_operator']) for (const width of [390, 1440]) {
  test(`${role} at ${width}px: direct links, permitted tabs, administration and forbidden sections`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 })
    await login(page, role, role === 'storekeeper' ? '/orders' : role === 'order_operator' ? '/supplies' : '/inventory')
    await expect(page).toHaveURL(role === 'storekeeper' || role === 'order_operator' ? '/' : '/inventory')
    const nav = await navigation(page, width)
    for (const [name, count] of [['Поставки', role === 'order_operator' ? 0 : 1], ['Заказы', role === 'storekeeper' ? 0 : 1], ['Аналитика', role === 'admin' || role === 'manager' ? 1 : 0], ['Админ-панель', role === 'admin' ? 1 : 0]] as const) await expect(nav.getByRole('link', { name, exact: true })).toHaveCount(count)
    await nav.getByRole('link', { name: 'Рекомендации', exact: true }).click()
    await expect(page).toHaveURL(role === 'storekeeper' ? '/recommendations/procurement' : '/recommendations/offers')
    const tabs = page.getByRole('navigation', { name: 'Вкладки рекомендаций' })
    await expect(tabs.getByRole('link', { name: 'Горячие предложения' })).toHaveCount(role === 'storekeeper' ? 0 : 1)
    await expect(tabs.getByRole('link', { name: 'Закупить продукты' })).toHaveCount(role === 'order_operator' ? 0 : 1)
    await page.reload()
    await expect(page.getByRole('heading', { name: 'Рекомендации', exact: true })).toBeVisible()
    const api: string[] = []
    page.on('request', (request) => { if (request.url().includes('/api/v1/')) api.push(new URL(request.url()).pathname) })
    await page.goto(role === 'storekeeper' ? '/orders' : role === 'order_operator' ? '/supplies' : '/admin/users')
    if (role === 'admin') {
      await expect(page.getByRole('heading', { name: 'Пользователи и роли', exact: true })).toBeVisible()
      await expect(page.getByRole('article', { name: 'Пользователь: Анна Администратор' })).toContainText('anna@example.test')
      await page.goto('/admin/settings')
      await expect(page.getByRole('heading', { name: 'Настройки ресторана', exact: true })).toBeVisible()
      await expect(page.getByRole('navigation', { name: 'Административные разделы' }).getByRole('link')).toHaveCount(6)
      await (await navigation(page, width)).getByRole('link', { name: 'Админ-панель', exact: true }).click()
      await expect(page).toHaveURL('/admin/products')
    } else {
      await expect(page.getByRole('heading', { name: 'Недостаточно прав' })).toBeVisible()
      await expect(page.getByText('Содержимое этого раздела появится на следующем этапе разработки.')).toHaveCount(0)
      expect(api).toContain('/api/v1/auth/me')
      expect(api.filter((path) => !['/api/v1/auth/me', '/api/v1/events'].includes(path))).toEqual([])
      await page.reload()
      await expect(page.getByRole('heading', { name: 'Недостаточно прав' })).toBeVisible()
      await page.getByRole('link', { name: 'К обзору' }).click()
      await expect(page).toHaveURL('/')
    }
    await page.goto('/unknown-route')
    await expect(page.getByRole('heading', { name: 'Страница не найдена' })).toBeVisible()
    await page.getByRole('link', { name: 'К обзору' }).click()
    await expect(page.getByRole('heading', { name: 'Обзор', exact: true })).toBeVisible()
    await page.goto('/forbidden')
    await expect(page.getByRole('heading', { name: 'Недостаточно прав' })).toBeVisible()
  })
}

test('loading session blocks shell until access is known', async ({ page, context }) => {
  await context.addCookies([{ name: 'flagman_mock_session', value: 'active', url: 'http://127.0.0.1:5182' }])
  await page.goto('/dev/api')
  await page.getByLabel('Сценарий API').selectOption('slow')
  await page.getByRole('link', { name: '← На главную' }).click()
  await expect(page.getByRole('status', { name: 'Проверяем сессию' })).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Разделы приложения' })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Обзор', exact: true })).toBeVisible()
})

test('server 403 retains session and draft; menu and Back block dirty transitions', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 1000 })
  await login(page)
  await expect(page).toHaveURL('/')
  await page.getByRole('link', { name: 'Проверить доступ и переходы' }).click()
  const draft = page.getByLabel('Тестовый черновик')
  await draft.fill('Заметка без секретов')
  await (await navigation(page, 390)).getByRole('link', { name: 'Склад', exact: true }).click()
  const guard = page.getByRole('dialog', { name: 'Уйти без сохранения?' })
  await expect(guard).toBeVisible()
  await expect(guard.getByRole('button', { name: 'Остаться' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page).toHaveURL('/dev/access')
  await expect(draft).toHaveValue('Заметка без секретов')
  await page.getByRole('button', { name: 'Выйти', exact: true }).click()
  await expect(guard).toBeVisible()
  await guard.getByRole('button', { name: 'Остаться' }).click()
  await expect(draft).toHaveValue('Заметка без секретов')
  const historyIndex = await page.evaluate(() => history.state.idx as number)
  await page.evaluate(() => history.back())
  await expect(guard).toBeVisible()
  await guard.getByRole('button', { name: 'Остаться' }).click()
  await expect(page).toHaveURL('/dev/access')
  await expect.poll(() => page.evaluate(() => history.state.idx as number)).toBe(historyIndex)
  await expect(guard).toBeHidden()
  await page.getByLabel('Сценарий API').selectOption('forbidden')
  await expect(page.getByRole('heading', { name: 'Недостаточно прав' })).toBeVisible()
  await expect(page.getByRole('banner').getByText('Тестовый сотрудник', { exact: true })).toBeVisible()
  await expect(page).toHaveURL('/dev/access')
  await page.getByLabel('Сценарий API').selectOption('success')
  await expect(draft).toHaveValue('Заметка без секретов')
  await (await navigation(page, 390)).getByRole('link', { name: 'Склад', exact: true }).click()
  await guard.getByRole('button', { name: 'Уйти без сохранения' }).click()
  await expect(page).toHaveURL('/inventory')
  await expect(page.getByRole('heading', { name: 'Склад', exact: true })).toBeVisible()
  await page.goBack()
  await expect(page).toHaveURL('/dev/access')
  await expect(draft).toHaveValue('')
})
