test('URL filters, category, sort and pages survive reload, history and navigation to supply/writeoff', async ({ page }) => {
  await login(page, '/inventory?page_size=20')
  const listPagination = page.getByRole('navigation', { name: 'Страницы списка' })
  await listPagination.getByRole('button', { name: 'Следующая страница' }).click()
  await expect(page).toHaveURL(/page=2/)
  await page.getByRole('button', { name: 'С просрочкой · 2' }).click()
  expect(new URL(page.url()).searchParams.has('page')).toBe(false)
  await expect(page.getByRole('article')).toHaveCount(2)
  await page.getByLabel('Поиск продукта').fill('Молоко')
  const searchResponse = page.waitForResponse((response) => { const url = new URL(response.url()); return url.pathname === '/api/v1/inventory' && url.searchParams.get('search') === 'Молоко' })
  await page.getByLabel('Поиск продукта').press('Enter')
  await searchResponse
  await expect.poll(() => new URL(page.url()).searchParams.get('search')).toBe('Молоко')
  const categoryResponse = page.waitForResponse((response) => { const url = new URL(response.url()); return url.pathname === '/api/v1/inventory' && url.searchParams.get('category_id') === '00000000-0000-4000-8000-000000000001' })
  await page.getByLabel('Категория', { exact: true }).selectOption('00000000-0000-4000-8000-000000000001')
  await categoryResponse
  await expect.poll(() => new URL(page.url()).searchParams.get('category_id')).toBe('00000000-0000-4000-8000-000000000001')
  const sortResponse = page.waitForResponse((response) => { const url = new URL(response.url()); return url.pathname === '/api/v1/inventory' && url.searchParams.get('sort') === 'nearest_expires_at' })
  await page.getByLabel('Сортировка продуктов').selectOption('nearest_expires_at')
  await sortResponse
  await expect.poll(() => new URL(page.url()).searchParams.get('sort')).toBe('nearest_expires_at')
  const query = new URL(page.url()).search
  await page.reload()
  await expect(page.getByLabel('Поиск продукта')).toHaveValue('Молоко')
  await expect(page.getByLabel('Сортировка продуктов')).toHaveValue('nearest_expires_at')
  await expect(page.getByLabel('Категория', { exact: true })).toHaveValue('00000000-0000-4000-8000-000000000001')
  await page.getByRole('button', { name: 'Раскрыть партии Молоко' }).click()
  await page.getByRole('link', { name: 'К поставке ТЕСТ-101, строка 1', exact: true }).click()
  await expect(page).toHaveURL('/supplies/00000000-0000-4000-8000-000000000100')
  await expect(page.getByRole('heading', { name: 'Детали поставки', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Поставка ТЕСТ-101', exact: true })).toBeVisible()
  await expect(page.getByRole('table', { name: 'Состав поставки' }).getByRole('row')).toHaveCount(28)
  await page.goBack()
  await expect(page).toHaveURL(`/inventory${query}`)
  await page.getByRole('button', { name: 'Раскрыть партии Молоко' }).click()
  await page.getByRole('link', { name: 'Списать партию · строка 1', exact: true }).click()
  const target = new URL(page.url())
  expect(target.pathname).toBe('/write-offs')
  expect(target.searchParams.get('batch_id')).toBe('00000000-0000-4000-8000-000000000201')
  await page.goBack()
  await expect(page.getByLabel('Поиск продукта')).toHaveValue('Молоко')
  await page.goForward()
  await expect(page).toHaveURL(/write-offs/)
  await page.goBack()
  await page.getByLabel('Категория', { exact: true }).selectOption('00000000-0000-4000-8000-000000000002')
  await expect(page.getByRole('heading', { name: 'Ничего не найдено' })).toBeVisible()
  await page.goBack()
  await expect(page.getByLabel('Категория', { exact: true })).toHaveValue('00000000-0000-4000-8000-000000000001')
  await expect(page.getByRole('article', { name: 'Молоко' })).toBeVisible()
})

test('independent loading/error/empty panels and list states; 403 retains session', async ({ page }) => {
  await login(page, '/inventory?search=Молоко')
  await page.getByLabel('Сценарий API').selectOption('batches-slow')
  await page.getByRole('button', { name: 'Раскрыть партии Молоко' }).click()
  await expect(page.getByRole('status', { name: 'Загрузка партий: Молоко' })).toBeVisible()
  await expect(page.getByRole('article', { name: 'Молоко' })).toBeVisible()
  await expect(page.getByText('ТЕСТ-101 · строка 1', { exact: true })).toBeVisible()
  await page.getByLabel('Сценарий API').selectOption('batches-error')
  await expect(page.getByRole('heading', { name: 'Не удалось загрузить партии' })).toBeVisible()
  await expect(page.getByRole('article', { name: 'Молоко' })).toBeVisible()
  await page.getByLabel('Сценарий API').selectOption('batches-empty')
  await expect(page.getByRole('heading', { name: 'Нет подходящих партий' })).toBeVisible()
  await page.getByLabel('Сценарий API').selectOption('categories-error')
  await expect(page.getByRole('heading', { name: 'Не удалось загрузить категории' })).toBeVisible()
  await expect(page.getByRole('article', { name: 'Молоко' })).toBeVisible()
  await page.getByLabel('Сценарий API').selectOption('slow')
  await expect(page.getByRole('status', { name: 'Загрузка склада' })).toBeVisible()
  await expect(page.getByRole('article', { name: 'Молоко' })).toBeVisible()
  await page.getByLabel('Сценарий API').selectOption('server-error')
  await expect(page.getByRole('heading', { name: 'Не удалось загрузить склад' })).toBeVisible()
  await expect(page.getByRole('article')).toHaveCount(0)
  await page.getByLabel('Сценарий API').selectOption('forbidden')
  await expect(page.getByRole('heading', { name: 'Недостаточно прав' }).first()).toBeVisible()
  await expect(page.getByRole('banner').getByText('Тестовый сотрудник', { exact: true })).toBeVisible()
  await page.getByLabel('Сценарий API').selectOption('success')
  await expect(page.getByRole('article', { name: 'Молоко' })).toBeVisible()
  await page.getByRole('button', { name: 'Сбросить фильтры' }).click()
  await page.getByLabel('Сценарий API').selectOption('inventory-empty')
  await expect(page.getByRole('heading', { name: 'Склад пока пуст' })).toBeVisible()
})

test('expired-only and zero-stock products; operator has no stock mutation or supply actions', async ({ page }) => {
  await login(page, '/inventory?filter=out_of_stock', 'order_operator')
  const expired = page.getByRole('article', { name: 'Творог — только просрочка' })
  await expect(expired).toBeVisible()
  await expect(expired.getByText('Нет годных партий')).toBeVisible()
  await expect(expired.getByText('Нет годного остатка', { exact: true })).toBeVisible()
  await expired.getByRole('button', { name: 'Раскрыть партии Творог — только просрочка' }).click()
  await expect(expired.getByText('Срок истёк 0 с назад')).toBeVisible()
  await expect(expired.getByRole('link', { name: /К поставке|Списать партию/ })).toHaveCount(0)
  const empty = page.getByRole('article', { name: 'Сахар' })
  await expect(empty.getByText('Не задан')).toBeVisible()
  await empty.getByRole('button', { name: 'Раскрыть партии Сахар' }).click()
  await expect(empty.getByRole('heading', { name: 'Нет подходящих партий' })).toBeVisible()
  await page.getByLabel('Поиск продукта').fill('Нет такого продукта')
  await page.getByRole('button', { name: 'Найти', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Ничего не найдено' })).toBeVisible()
  await page.getByRole('button', { name: 'Сбросить фильтры' }).first().click()
  await page.getByLabel('Поиск продукта').fill('Мука')
  await page.getByRole('button', { name: 'Найти', exact: true }).click()
  await expect(page.getByRole('article', { name: 'Мука' }).getByText('199999999,999998 кг', { exact: true }).first()).toBeVisible()
})
